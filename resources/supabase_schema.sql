-- CAMPUSOS Supabase PostgreSQL schema.
-- Run in the Supabase SQL Editor for a new project. Review before applying to a database with existing data.
-- PostgreSQL uses identity columns and CHECK constraints instead of MySQL AUTO_INCREMENT/ENUM.

create extension if not exists btree_gist;

create table if not exists public.users (
    id integer generated by default as identity primary key,
    name varchar(100) not null,
    email varchar(150) not null unique,
    password varchar(255) not null,
    role varchar(20) not null check (role in ('STUDENT','FACULTY','MAINTENANCE','TECHNICIAN','ADMIN')),
    register_number varchar(50),
    department varchar(100),
    specialization varchar(100),
    available boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.issues (
    id integer generated by default as identity primary key,
    title varchar(200) not null,
    description text not null,
    category varchar(100) not null,
    location varchar(200),
    attachment_path varchar(500),
    priority varchar(10) not null default 'LOW' check (priority in ('LOW','MEDIUM','HIGH','CRITICAL')),
    created_at timestamptz not null default now()
);

create table if not exists public.tickets (
    id integer generated by default as identity primary key,
    issue_id integer not null references public.issues(id),
    reported_by integer not null references public.users(id),
    assigned_technician_id integer references public.users(id),
    status varchar(20) not null default 'OPEN' check (status in ('OPEN','ASSIGNED','IN_PROGRESS','RESOLVED','CLOSED')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create or replace function public.campusos_touch_updated_at()
returns trigger language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists tickets_touch_updated_at on public.tickets;
create trigger tickets_touch_updated_at
before update on public.tickets
for each row execute function public.campusos_touch_updated_at();

create table if not exists public.resources (
    id integer generated by default as identity primary key,
    name varchar(150) not null,
    type varchar(100) not null,
    quantity integer not null default 0 check (quantity >= 0),
    available boolean not null default true
);

create table if not exists public.bookings (
    id integer generated by default as identity primary key,
    resource_id integer not null references public.resources(id),
    booked_by integer not null references public.users(id),
    start_time timestamp without time zone not null,
    end_time timestamp without time zone not null,
    check (start_time < end_time),
    constraint bookings_no_overlapping_times
        exclude using gist (resource_id with =, tsrange(start_time, end_time, '[)') with &&)
);

create table if not exists public.notifications (
    id integer generated by default as identity primary key,
    user_id integer not null references public.users(id),
    message text not null,
    is_read boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.emergencies (
    id integer generated by default as identity primary key,
    title varchar(200) not null,
    message text not null,
    created_by integer not null references public.users(id),
    created_at timestamptz not null default now()
);

create index if not exists idx_users_role on public.users(role);
create index if not exists idx_tickets_status on public.tickets(status);
create index if not exists idx_tickets_reported_by_created on public.tickets(reported_by, created_at desc);
create index if not exists idx_tickets_assignee_status on public.tickets(assigned_technician_id, status);
create index if not exists idx_issues_priority on public.issues(priority);
create index if not exists idx_notifications_user_read_created on public.notifications(user_id, is_read, created_at desc);
create index if not exists idx_bookings_resource_start on public.bookings(resource_id, start_time);

