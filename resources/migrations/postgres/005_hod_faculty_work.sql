-- CAMPUSOS HOD / faculty work management.
-- Apply once to an existing PostgreSQL/Supabase database after reviewing.
-- HOD is represented by the existing ADMIN role; professors use FACULTY.
CREATE TABLE IF NOT EXISTS public.faculty_work_invitations (
    id integer generated by default as identity primary key,
    name varchar(100) not null,
    email varchar(150) not null,
    department varchar(100),
    token_hash char(64) not null unique,
    invited_by integer not null references public.users(id),
    expires_at timestamptz not null,
    accepted_at timestamptz,
    created_at timestamptz not null default now()
);
CREATE INDEX IF NOT EXISTS idx_faculty_work_invites_email_expiry
    ON public.faculty_work_invitations(email, expires_at);

CREATE TABLE IF NOT EXISTS public.faculty_work_assignments (
    id integer generated by default as identity primary key,
    title varchar(200) not null,
    description text not null,
    assigned_to integer not null references public.users(id),
    assigned_by integer not null references public.users(id),
    due_at timestamptz,
    status varchar(20) not null default 'PENDING'
        check (status in ('PENDING','IN_PROGRESS','COMPLETED')),
    progress_percent integer not null default 0
        check (progress_percent between 0 and 100),
    progress_note varchar(2000),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
CREATE INDEX IF NOT EXISTS idx_faculty_work_assignee_status_due
    ON public.faculty_work_assignments(assigned_to, status, due_at);
CREATE INDEX IF NOT EXISTS idx_faculty_work_status_due
    ON public.faculty_work_assignments(status, due_at);

DROP TRIGGER IF EXISTS faculty_work_assignments_touch_updated_at
    ON public.faculty_work_assignments;
CREATE TRIGGER faculty_work_assignments_touch_updated_at
BEFORE UPDATE ON public.faculty_work_assignments
FOR EACH ROW EXECUTE FUNCTION public.campusos_touch_updated_at();

-- Explicit least-privilege grants for the existing JDBC application role.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'campusos_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON TABLE public.faculty_work_invitations TO campusos_app';
        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON TABLE public.faculty_work_assignments TO campusos_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.faculty_work_invitations_id_seq TO campusos_app';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.faculty_work_assignments_id_seq TO campusos_app';
    END IF;
END
$$;
