-- Apply only to an existing CAMPUSOS PostgreSQL database whose core tables already exist.
-- For a new database, run resources/supabase_schema.sql instead.
create table if not exists public.ticket_history (
    id integer generated by default as identity primary key,
    ticket_id integer not null references public.tickets(id),
    changed_by integer references public.users(id),
    previous_status varchar(20) not null,
    new_status varchar(20) not null,
    created_at timestamptz not null default now()
);
alter table public.ticket_history alter column changed_by drop not null;
create index if not exists idx_ticket_history_ticket_created on public.ticket_history(ticket_id, created_at);
create index if not exists idx_tickets_reported_by_created on public.tickets(reported_by, created_at desc);
create index if not exists idx_tickets_assignee_status on public.tickets(assigned_technician_id, status);
create index if not exists idx_bookings_resource_start on public.bookings(resource_id, start_time);
create index if not exists idx_bookings_user_start on public.bookings(booked_by, start_time);
create index if not exists idx_emergencies_created on public.emergencies(created_at desc);
